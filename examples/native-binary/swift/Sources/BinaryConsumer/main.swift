 encodeState: { [UInt8($0)] }, decodeState: scalar, encodeInput: { [UInt8($0)] }, decodeInput: scalar, encodeOutput: { $0 }))
let config = RunConfig(strategy: "manual")
let args = CommandLine.arguments
guard args.count >= 3 else { throw ModelError("expected generate, roundtrip, or replay-single") }
let mode = args[1]
var receipt: [String: Any]
func load(_ path: String) throws -> [UInt8] { Array(try Data(contentsOf: URL(fileURLWithPath: path))) }
