import Foundation
import Statelessness

func scalar(_ value: [UInt8]) throws -> Int {
 guard value.count == 1 else { throw ModelError("expected one byte") }; return Int(value[0])
}
let model = Model<Int, Int, [UInt8]>(initialState: { 0 },
 step: { before, input in Transition(state: before + 2 * input, outputs: [[], [UInt8(before), 255]]) },
 checkState: { _ in [.passed("ok")] }, cloneState: { $0 }, cloneInput: { $0 }, cloneOutput: { $0 },
 checkTransition: { _, _, _ in [.skipped("later", "not run")] },
