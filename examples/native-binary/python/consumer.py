"""Installed public binary codec + compatible application model consumer."""
import json
from pathlib import Path
import sys
import statelessness
from statelessness import Check, Metadata, Transition, record, replay
from statelessness.trace_binary import AuditTrace, RunConfig, audit_from_bytes, audit_to_bytes


class Counter:
    def initial_state(self): return 0
    def step(self, before, input): return Transition(before + 2 * input, (b"", bytes((before, 255))))
    def check_state(self, state): return (Check("ok"),)
    def check_transition(self, before, input, transition): return (Check("later", "skipped", "not run"),)
    def metadata(self): return Metadata("counter", 1, 2, 3, "b")
    def encode_state(self, state): return bytes((state,))
    def decode_state(self, data):
        if len(data) != 1: raise ValueError("expected one byte")
        return data[0]
    def encode_input(self, input): return bytes((input,))
    def decode_input(self, data): return self.decode_state(data)
    def encode_output(self, output): return output


mode = sys.argv[1]
if mode == "generate":
    case, output, corpus = sys.argv[2:]
    fixture, = (f for f in json.loads(Path(corpus).read_text())["fixtures"] if f["case"] == case and f["valid"])
    expected = bytes.fromhex(fixture["bytes_hex"])
    audit = audit_from_bytes(expected)
    encoded = audit_to_bytes(audit)
    if encoded != expected: raise RuntimeError("generated bytes differ from corpus")
    Path(output).write_bytes(encoded)
    receipt = {"case": case, "exact_byte_roundtrip": True, "native_record": False, "semantic_replay": False}
elif mode == "record-single":
    audit = AuditTrace.from_portable(record(Counter(), [1]), RunConfig("manual", None, ()))
    Path(sys.argv[2]).write_bytes(audit_to_bytes(audit))
    receipt = {"native_record": True, "semantic_replay": False, "steps": len(audit.steps),
               "config": {"strategy": audit.config.strategy, "seed": None, "parameters": audit.config.parameters}}
elif mode == "roundtrip":
    source, output = sys.argv[2:]
    original = Path(source).read_bytes()
    encoded = audit_to_bytes(audit_from_bytes(original))
    if encoded != original: raise RuntimeError("binary read/write changed bytes")
    Path(output).write_bytes(encoded)
    receipt = {"exact_byte_roundtrip": True, "semantic_replay": False}
elif mode == "replay-single":
    audit = audit_from_bytes(Path(sys.argv[2]).read_bytes())
    if audit.termination == "model_error": raise RuntimeError("terminal model error cannot be reproduced by prefix replay")
    trace, retained_config = audit.to_portable()
    if retained_config.strategy != "manual" or retained_config.seed is not None: raise RuntimeError("unexpected replay config")
    result = replay(Counter(), trace)
    receipt = {"semantic_replay": result.outcome == "exact", "outcome": result.outcome, "failure_reproduced": result.failure_reproduced, "steps": len(trace.steps),
               "retained_config": {"strategy": retained_config.strategy, "seed": None if retained_config.seed is None else str(retained_config.seed),
                                   "parameters": retained_config.parameters}}
else:
    raise ValueError("expected generate, roundtrip, or replay-single")
print(json.dumps(dict(receipt, package=str(Path(statelessness.__file__).resolve()))))
