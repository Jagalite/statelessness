package main

import (
 "bytes"
 "encoding/hex"
 "encoding/json"
 "fmt"
 "os"
 s "github.com/Jagalite/statelessness/go"
)

func must(err error){if err!=nil{panic(err)}}
func scalar(v []byte)(int,error){if len(v)!=1{return 0,fmt.Errorf("expected one byte")};return int(v[0]),nil}
func main(){
 model:=s.Model[int,int,[]byte]{
  InitialState:func()(int,error){return 0,nil},
  Step:func(before,input int)(s.Transition[int,[]byte],error){return s.Accept[int,[]byte](before+2*input,[]byte{},[]byte{byte(before),255}),nil},
  CheckState:func(int)([]s.Check,error){return []s.Check{s.Passed("ok")},nil},
  CheckTransition:func(int,int,s.Transition[int,[]byte])([]s.Check,error){return []s.Check{s.Skipped("later","not run")},nil},
  CloneState:s.ValueCopy[int],CloneInput:s.ValueCopy[int],CloneOutput:func(v []byte)[]byte{return append([]byte{},v...)},
  Codec:&s.Codec[int,int,[]byte]{Metadata:func()(s.Metadata,error){return s.Metadata{Name:"counter",ModelVersion:1,PropertiesVersion:2,CodecVersion:3,Build:"b"},nil},
   EncodeState:func(v int)([]byte,error){return []byte{byte(v)},nil},DecodeState:scalar,EncodeInput:func(v int)([]byte,error){return []byte{byte(v)},nil},DecodeInput:scalar,
   EncodeOutput:func(v []byte)([]byte,error){return append([]byte{},v...),nil}},
 }
 if len(os.Args)<3{panic("expected generate, roundtrip, or replay-single")}
 mode:=os.Args[1];receipt:=map[string]any{}
 switch mode{
 case "generate":
  if len(os.Args)!=5{panic("generate CASE OUTPUT CORPUS")};name,output,corpus:=os.Args[2],os.Args[3],os.Args[4]
  corpusData,err:=os.ReadFile(corpus);must(err)
  var fixtureData struct{Fixtures []struct{Case string `json:"case"`;Valid bool `json:"valid"`;Hex string `json:"bytes_hex"`} `json:"fixtures"`}
  must(json.Unmarshal(corpusData,&fixtureData));var expected []byte;found:=false
  for _,f:=range fixtureData.Fixtures{if f.Case==name&&f.Valid{expected,err=hex.DecodeString(f.Hex);must(err);found=true;break}}
  if !found{panic("valid fixture missing")};var audit *s.AuditTrace
  audit,err=s.ParseAuditTrace(expected,s.DefaultBinaryLimits());must(err)
  encoded,err:=s.MarshalAuditTrace(audit,s.DefaultBinaryLimits());must(err);if !bytes.Equal(encoded,expected){panic("generated bytes differ from corpus")};must(os.WriteFile(output,encoded,0600))
  receipt=map[string]any{"case":name,"exact_byte_roundtrip":true,"native_record":false,"semantic_replay":false}
 case "record-single":
  trace,err:=s.Record(model,s.Values([]int{1}),10);must(err);audit,err:=s.AuditFromPortable(*trace,s.RunConfig{Strategy:"manual",Parameters:[][2]string{}});must(err)
  encoded,err:=s.MarshalAuditTrace(audit,s.DefaultBinaryLimits());must(err);must(os.WriteFile(os.Args[2],encoded,0600))
  parameters:=audit.Config.Parameters;if parameters==nil{parameters=[][2]string{}}
  receipt=map[string]any{"native_record":true,"semantic_replay":false,"steps":len(audit.Steps),"config":map[string]any{"strategy":audit.Config.Strategy,"seed":nil,"parameters":parameters}}
 case "roundtrip":
  if len(os.Args)!=4{panic("roundtrip INPUT OUTPUT")};original,err:=os.ReadFile(os.Args[2]);must(err)
  audit,err:=s.ParseAuditTrace(original,s.DefaultBinaryLimits());must(err);encoded,err:=s.MarshalAuditTrace(audit,s.DefaultBinaryLimits());must(err)
  if !bytes.Equal(encoded,original){panic("binary read/write changed bytes")};must(os.WriteFile(os.Args[3],encoded,0600));receipt=map[string]any{"exact_byte_roundtrip":true,"semantic_replay":false}
 case "replay-single":
  original,err:=os.ReadFile(os.Args[2]);must(err);audit,err:=s.ParseAuditTrace(original,s.DefaultBinaryLimits());must(err)
  if audit.Termination=="model_error"{panic("terminal model error cannot be reproduced by prefix replay")}
  trace,config,err:=audit.Portable();must(err);if config.Strategy!="manual"||config.Seed!=nil{panic("unexpected replay config")}
  result,err:=s.Replay(model,&trace,false);must(err)
  parameters:=config.Parameters;if parameters==nil{parameters=[][2]string{}}
  receipt=map[string]any{"semantic_replay":result.Outcome=="exact","outcome":result.Outcome,"failure_reproduced":result.FailureReproduced,"steps":len(trace.Steps),"retained_config":map[string]any{"strategy":config.Strategy,"seed":nil,"parameters":parameters}}
 default:panic("expected generate, roundtrip, or replay-single")
 }
 must(json.NewEncoder(os.Stdout).Encode(receipt))
}
