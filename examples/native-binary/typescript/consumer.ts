import {accepted,check,record,replay,auditTraceFromPortable,auditTraceToPortable,readAuditTrace,writeAuditTrace,
 type CodecModel} from '@jagalite/statelessness';
declare const process: {argv:string[]};
// @ts-ignore Runtime built-in; the consumer has no @types/node dependency.
import {readFileSync,writeFileSync} from 'node:fs';
const byte=(v:Uint8Array):number=>{if(v.length!==1)throw Error('expected one byte');return v[0];};
const model:CodecModel<number,number,Uint8Array>={
 initialState:()=>0,step:(before,input)=>accepted(before+2*input,[new Uint8Array(),new Uint8Array([before,255])]),
 checkState:()=>[check('ok')],checkTransition:()=>[check('later','skipped','not run')],
 cloneState:v=>v,cloneInput:v=>v,cloneOutput:v=>v.slice(),
 metadata:()=>({name:'counter',model_version:1,properties_version:2,codec_version:3,build:'b'}),
 encodeState:v=>new Uint8Array([v]),decodeState:byte,encodeInput:v=>new Uint8Array([v]),decodeInput:byte,encodeOutput:v=>v.slice(),
};
const config={strategy:'manual',seed:null,parameters:[]};
const bytes=(hex:string):Uint8Array=>new Uint8Array(hex.match(/../g)?.map(b=>parseInt(b,16))??[]);
const equal=(a:Uint8Array,b:Uint8Array):boolean=>a.length===b.length&&a.every((v,i)=>v===b[i]);
const [mode,...args]=process.argv.slice(2);
let receipt:Record<string,unknown>;
if(mode==='generate'){
 const [name,output,corpus]=args;
 const fixture=JSON.parse(readFileSync(corpus,'utf8')).fixtures.find((f:{case:string,valid:boolean})=>f.case===name&&f.valid);
 if(!fixture)throw Error('valid fixture missing');
 const expected=bytes(fixture.bytes_hex);
 const audit=readAuditTrace(expected);
 const encoded=writeAuditTrace(audit);
 if(!equal(encoded,expected))throw Error('generated bytes differ from corpus');
 writeFileSync(output,encoded);
 receipt={case:name,exact_byte_roundtrip:true,native_record:false,semantic_replay:false};
}else if(mode==='record-single'){
 const audit=auditTraceFromPortable(record(model,[1]),config);
 writeFileSync(args[0],writeAuditTrace(audit));
 receipt={native_record:true,semantic_replay:false,steps:audit.steps.length,config};
}else if(mode==='roundtrip'){
 const [input,output]=args,original:Uint8Array=readFileSync(input);
 const encoded=writeAuditTrace(readAuditTrace(original));
 if(!equal(encoded,original))throw Error('binary read/write changed bytes');
 writeFileSync(output,encoded);receipt={exact_byte_roundtrip:true,semantic_replay:false};
}else if(mode==='replay-single'){
 const audit=readAuditTrace(readFileSync(args[0]));
 if(audit.termination==='model_error')throw Error('terminal model error cannot be reproduced by prefix replay');
 const projection=auditTraceToPortable(audit);
 if(projection.config.strategy!=='manual'||projection.config.seed!==null)throw Error('unexpected replay config');
 const result=replay(model,projection.trace);
 receipt={semantic_replay:result.outcome==='exact',outcome:result.outcome,failure_reproduced:result.failure_reproduced,steps:projection.trace.steps.length,
  retained_config:{strategy:projection.config.strategy,seed:projection.config.seed===null?null:String(projection.config.seed),parameters:projection.config.parameters}};
}else throw Error('expected generate, roundtrip, or replay-single');
console.log(JSON.stringify(receipt));
