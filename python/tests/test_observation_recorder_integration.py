"""N07 source-authored integration: the application owns execution and effects.

Uses the existing checked tokens, Recorder, binary format and public replay API.
No fixture is generated by running an observer. All execution, including the
fresh-process replay assertions, awaits the parent's integrated Kyoto run.
"""
import io
import json
import subprocess
import sys
import unittest
from collections import Counter

from statelessness import (
    Check, CheckPolicy, Disposition, Metadata, ModelError, RunConfig, Transition,
    audit_to_bytes,
)
from statelessness.checked import check_initial, check_turn
from statelessness.monitor import Recorder, RecorderOptions
from statelessness.observation import (
    EncodedPayloads, Event, LogLevel, ObservationOptions, SnapshotPolicy,
    TextObserver, TextObserverError,
)
from statelessness.replay_evidence import replay_with_observations_bounded


class ApplicationModel:
    def __init__(self, *, fail_at=None, skip_at=None):
        self.calls = Counter()
        self.fail_at, self.skip_at = fail_at, skip_at
        self.fail_encode_input = False
        self.last_checked = None

    def metadata(self):
        self.calls['metadata'] += 1
        return Metadata('observation-recorder-integration', build='source-authored-v1')

    def initial_state(self):
        self.calls['initial'] += 1
        raise AssertionError('application supplies the checkpoint')

    def step(self, state, input):
        self.calls['step'] += 1
        if input > 0:
            state += input
            disposition = Disposition()
        elif input == 0:
            disposition = Disposition('rejected', 'application rejected')
        else:
            disposition = Disposition('ignored', 'application ignored')
        return Transition(state, (state + 10000, -state), disposition)

    def check_state(self, state):
        self.calls['state_check'] += 1
        checks = [Check('state')]
        if state % 2 == 0:
            checks.append(Check('even-state'))
        if state == self.skip_at:
            checks.append(Check('optional', 'skipped', 'application skipped'))
        if state == self.fail_at:
            checks.append(Check('limit', 'failed', 'first property failure'))
        return tuple(checks)

    def check_transition(self, before, input, transition):
        self.calls['turn_check'] += 1
        self.last_checked = (before, input, transition)
        if transition.outputs != (transition.state + 10000, -transition.state):
            return (Check('actual-output', 'failed', 'supplied outputs differ'),)
        return (Check('actual-output'),)

    def encode_state_into(self, value, out):
        self.calls['encode_state'] += 1
        out.append(str(value).encode('ascii'))

    def encode_input_into(self, value, out):
        self.calls['encode_input'] += 1
        if self.fail_encode_input:
            raise ModelError('diagnostic codec failure')
        out.append(str(value).encode('ascii'))

    def encode_output_into(self, value, out):
        self.calls['encode_output'] += 1
        out.append(str(value).encode('ascii'))

    def decode_state(self, value):
        return int(value)

    def decode_input(self, value):
        return int(value)


def apply(model, before, input):
    """The sole application reducer/effect path, never called by diagnostics."""
    transition = model.step(before, input)
    for _ in transition.outputs:
        model.calls['effect'] += 1
    return transition


def event(token):
    return Event.Transition(token.sequence, token.before, token.input,
                            token.transition, token.checks)


def execution_counts(model):
    return tuple(model.calls[name] for name in
                 ('initial', 'step', 'state_check', 'turn_check', 'effect'))


class LastRecordWriter:
    """Bounded test sink: retains one record, never the whole long-session log."""
    def __init__(self):
        self.last = b''
        self.writes = self.total_bytes = self.max_bytes = 0

    def write(self, data):
        self.last = bytes(data)
        self.writes += 1
        self.total_bytes += len(data)
        self.max_bytes = max(self.max_bytes, len(data))
        return len(data)

    def flush(self):
        pass


class SwitchPayloads(EncodedPayloads):
    fault = None

    def input(self, model, value, out):
        if self.fault == 'format':
            raise ValueError('diagnostic formatter failure')
        if self.fault == 'overflow':
            # Even swallowing a rejected write cannot commit a partial record.
            try:
                out.write(b'x' * 4096)
            except OSError:
                pass
        super().input(model, value, out)


class ObservationRecorderIntegrationTests(unittest.TestCase):
    def test_all_levels_share_authentic_checks_and_match_uninstrumented_application(self):
        inputs = (1, 0, -1, 1, 1)
        baseline, state = ApplicationModel(), 0
        actual = []
        for input in inputs:
            transition = apply(baseline, state, input)
            actual.append(transition)
            state = transition.state
        self.assertEqual(execution_counts(baseline), (0, 5, 0, 0, 10))
        self.assertEqual(sum(baseline.calls[k] for k in
                             ('metadata', 'encode_state', 'encode_input', 'encode_output')), 0)
        reference = None
        for level in LogLevel:
            with self.subTest(level=level):
                model = ApplicationModel(fail_at=3, skip_at=2)
                initial = check_initial(model, 0)
                recorder = Recorder.with_checked_initial(initial, options=RecorderOptions(2))
                writer = io.BytesIO()
                observer = TextObserver(writer, 'app', ObservationOptions(
                    level, SnapshotPolicy.EVERY_TRANSITION, 1024), EncodedPayloads(32))
                observer.observe(model, Event.Checkpoint(0, initial.state, initial.checks))
                state = 0
                for sequence, (input, expected) in enumerate(zip(inputs, actual), 1):
                    transition = apply(model, state, input)
                    self.assertEqual(transition, expected)
                    token = check_turn(model, state, input, transition, sequence)
                    self.assertEqual(model.last_checked, (state, input, transition))
                    before = execution_counts(model)
                    self.assertEqual(recorder.observe_checked(token), token.checks)
                    observer.observe(model, event(token))
                    self.assertEqual(execution_counts(model), before)
                    state = transition.state
                self.assertEqual(execution_counts(model), (0, 5, 6, 5, 10))
                self.assertEqual(model.calls['metadata'], 6)
                self.assertEqual((model.calls['step'], model.calls['effect']),
                                 (baseline.calls['step'], baseline.calls['effect']))
                trace = recorder.snapshot()
                self.assertTrue(recorder.is_frozen())
                self.assertEqual(trace.termination, 'property_failed')
                blob = audit_to_bytes(trace)
                if reference is None:
                    reference = blob
                self.assertEqual(blob, reference)
                extra = 1 if level == LogLevel.TRACE else 0
                self.assertEqual(model.calls['encode_state'], 11 + 6 * extra)
                self.assertEqual(model.calls['encode_input'], 5 + 5 * extra)
                self.assertEqual(model.calls['encode_output'], 10 + 10 * extra)
                text = writer.getvalue().decode('utf-8')
                self.assertEqual(len(text.splitlines()), (0, 1, 2, 2, 5, 6)[int(level)])
                if level >= LogLevel.ERROR:
                    self.assertIn('Error stream="app" event=transition sequence=5', text)
                    self.assertIn('check="limit":Failed("first property failure")', text)
                if level >= LogLevel.WARN:
                    self.assertIn('Warn stream="app" event=transition sequence=4', text)
                    self.assertIn('check="optional":Skipped("application skipped")', text)
                if level >= LogLevel.DEBUG:
                    self.assertIn('disposition=Rejected("application rejected") outputs=2', text)
                    self.assertIn('disposition=Ignored("application ignored") outputs=2', text)
                if level == LogLevel.TRACE:
                    for field in ('input=hex:31', 'output[0]=hex:3130303031',
                                  'output[1]=hex:2d31', 'post_state=hex:31',
                                  'check="actual-output":Passed'):
                        self.assertIn(field, text)
                else:
                    self.assertNotIn('hex:', text)
                replay_model = ApplicationModel(fail_at=3, skip_at=2)
                report = replay_with_observations_bounded(replay_model, trace)
                self.assertEqual(report.outcome, 'exact')
                self.assertTrue(report.failure_reproduced)
                self.assertEqual(execution_counts(replay_model), (0, 2, 3, 2, 0))

    def test_long_sessions_keep_bounded_complete_suffix_and_absolute_snapshot_sequences(self):
        turns, initial_state = 1024, 10
        for level in LogLevel:
            for origin in (0, 9001):
                for capacity in (1, 2):
                    with self.subTest(level=level, origin=origin, capacity=capacity):
                        model = ApplicationModel()
                        initial = check_initial(model, initial_state)
                        options = RecorderOptions(capacity, max_retained_bytes=4096)
                        recorder = Recorder.with_checked_initial_at(initial, origin, options=options)
                        sink = LastRecordWriter()
                        observer = TextObserver(sink, 'long', ObservationOptions(
                            level, SnapshotPolicy.every(7), 1024), EncodedPayloads(32))
                        observer.observe(model, Event.Checkpoint(origin, initial.state, initial.checks))
                        state = initial_state
                        for local in range(1, turns + 1):
                            transition = apply(model, state, 1)
                            token = check_turn(model, state, 1, transition, origin + local)
                            before = execution_counts(model)
                            recorder.observe_checked(token)
                            observer.observe(model, event(token))
                            self.assertEqual(execution_counts(model), before)
                            self.assertLessEqual(recorder.retained_steps(), capacity)
                            self.assertLessEqual(recorder.retained_bytes(), options.max_retained_bytes)
                            self.assertLessEqual(sink.max_bytes, 1024)
                            state = transition.state
                        observer.observe(model, Event.Checkpoint(
                            origin + turns, token.transition.state,
                            token.checks[:token.state_check_count]))
                        self.assertEqual(execution_counts(model), (0, turns, turns + 1, turns, turns * 2))
                        self.assertEqual(model.calls['metadata'], turns + 1)
                        trace = recorder.snapshot()
                        self.assertFalse(recorder.is_frozen())
                        self.assertEqual((recorder.observed_steps(), recorder.evicted_steps(),
                                          recorder.retained_steps()), (turns, turns - capacity, capacity))
                        checkpoint = initial_state + turns - capacity
                        self.assertEqual(trace.initial_state, str(checkpoint).encode())
                        expected_checks = (Check('state'),) + ((Check('even-state'),) if checkpoint % 2 == 0 else ())
                        self.assertEqual(trace.initial_checks, expected_checks)
                        self.assertNotIn(Check('actual-output'), trace.initial_checks)
                        self.assertEqual([int(step.post_state) for step in trace.steps],
                                         list(range(checkpoint + 1, initial_state + turns + 1)))
                        self.assertTrue(all(step.input == b'1' and len(step.outputs) == 2
                                            and step.checks[-1] == Check('actual-output') for step in trace.steps))
                        parameters = dict(trace.config.parameters)
                        self.assertEqual(parameters['stateless.monitor.checkpoint_after_sequence'], str(turns - capacity))
                        self.assertEqual(parameters.get('stateless.monitor.sequence_origin', '0'), str(origin))
                        self.assertEqual(recorder.retained_bytes(), len(audit_to_bytes(trace)))
                        selected = (origin + turns) // 7 - origin // 7
                        trace_level = level == LogLevel.TRACE
                        self.assertEqual(model.calls['encode_state'], 1 + 2 * turns + (selected + 2 if trace_level else 0))
                        self.assertEqual(model.calls['encode_input'], turns * (2 if trace_level else 1))
                        self.assertEqual(model.calls['encode_output'], 2 * turns * (2 if trace_level else 1))
                        self.assertEqual(sink.writes, turns + 2 if trace_level else turns if level == LogLevel.DEBUG else 0)
                        if trace_level:
                            self.assertIn(f'event=checkpoint sequence={origin + turns}'.encode(), sink.last)
                            self.assertIn(b' state=hex:', sink.last)
                        replay_model = ApplicationModel()
                        report = replay_with_observations_bounded(replay_model, trace)
                        self.assertEqual(report.outcome, 'exact')
                        self.assertEqual(report.steps_verified, capacity)
                        self.assertEqual(execution_counts(replay_model), (0, capacity, capacity + 1, capacity, 0))
                        if level == LogLevel.TRACE and capacity == 1:
                            # A separate interpreter receives only serialized evidence
                            # and the independently authored model, never a live token.
                            source = '''
import importlib.util, json, sys
sys.path[:] = json.loads(sys.argv[2])
from statelessness import audit_from_bytes
from statelessness.replay_evidence import replay_with_observations_bounded
spec = importlib.util.spec_from_file_location('integration_model', sys.argv[1])
module = importlib.util.module_from_spec(spec)
spec.loader.exec_module(module)
model = module.ApplicationModel()
trace = audit_from_bytes(sys.stdin.buffer.read())
report = replay_with_observations_bounded(model, trace)
print(json.dumps(dict(outcome=report.outcome, steps=report.steps_verified,
                      failure=report.failure_reproduced,
                      counts=module.execution_counts(model),
                      checkpoint=int(trace.initial_state))))
'''
                            child = subprocess.run(
                                [sys.executable, '-c', source, __file__, json.dumps(sys.path)],
                                input=audit_to_bytes(trace), stdout=subprocess.PIPE,
                                stderr=subprocess.PIPE, timeout=30, check=False)
                            self.assertEqual(child.returncode, 0, child.stderr.decode('utf-8', 'replace'))
                            self.assertEqual(json.loads(child.stdout), dict(
                                outcome='exact', steps=1, failure=False,
                                counts=[0, 1, 2, 1, 0], checkpoint=checkpoint))

    def test_zero_capacity_is_rejected_without_running_application_callbacks(self):
        model = ApplicationModel()
        with self.assertRaisesRegex(ValueError, 'positive'):
            Recorder.with_options(model, 0, RunConfig(), RecorderOptions(0))
        self.assertEqual(model.calls, Counter())

    def test_format_codec_and_record_limit_errors_recover_without_touching_recorded_failure(self):
        for fault in ('format', 'codec', 'overflow'):
            with self.subTest(fault=fault):
                model = ApplicationModel(fail_at=3)
                initial = check_initial(model, 0)
                recorder = Recorder.with_checked_initial(initial, options=RecorderOptions(2))
                payloads, writer = SwitchPayloads(32), io.BytesIO()
                observer = TextObserver(writer, 'fault', ObservationOptions(
                    LogLevel.TRACE, SnapshotPolicy.EVERY_TRANSITION, 1024), payloads)
                state = 0
                for sequence in range(1, 4):
                    transition = apply(model, state, 1)
                    token = check_turn(model, state, 1, transition, sequence)
                    recorder.observe_checked(token)
                    prefix, before = recorder.snapshot(), execution_counts(model)
                    payloads.fault = fault
                    model.fail_encode_input = fault == 'codec'
                    delivered = writer.getvalue()
                    with self.assertRaises(TextObserverError):
                        observer.observe(model, event(token))
                    self.assertEqual(writer.getvalue(), delivered)
                    self.assertFalse(observer.sink_poisoned)
                    self.assertEqual(recorder.snapshot(), prefix)
                    self.assertEqual(execution_counts(model), before)
                    payloads.fault, model.fail_encode_input = None, False
                    observer.observe(model, event(token))
                    self.assertEqual(execution_counts(model), before)
                    self.assertEqual(recorder.snapshot(), prefix)
                    state = transition.state
                failure = recorder.snapshot()
                recorder.stop_with_error(ModelError('later diagnostic failure'))
                self.assertEqual(recorder.snapshot(), failure)
                self.assertEqual(failure.termination, 'property_failed')
                self.assertEqual(execution_counts(model), (0, 3, 4, 3, 6))
                report = replay_with_observations_bounded(ApplicationModel(fail_at=3), failure)
                self.assertEqual(report.outcome, 'exact')
                self.assertTrue(report.failure_reproduced)

    def test_sink_failure_poison_does_not_stop_recording_or_replace_first_property_failure(self):
        class BrokenSink:
            def __init__(self, flush_failure):
                self.flush_failure, self.calls, self.delivered = flush_failure, 0, b''

            def write(self, value):
                self.calls += 1
                if self.flush_failure:
                    self.delivered += bytes(value)
                    return len(value)
                if not self.delivered:
                    self.delivered = bytes(value[:3])
                    return 3
                raise OSError('write failed after prefix')

            def flush(self):
                self.calls += 1
                raise OSError('flush failed')

        for flush_failure in (False, True):
            with self.subTest(flush_failure=flush_failure):
                model = ApplicationModel(fail_at=3)
                recorder = Recorder.with_checked_initial(check_initial(model, 0), options=RecorderOptions(1))
                sink = BrokenSink(flush_failure)
                observer = TextObserver(sink, 'sink', ObservationOptions(LogLevel.DEBUG))
                state = 0
                for sequence in range(1, 4):
                    transition = apply(model, state, 1)
                    token = check_turn(model, state, 1, transition, sequence)
                    recorder.observe_checked(token)
                    prefix, before = recorder.snapshot(), execution_counts(model)
                    if sequence == 1 and flush_failure:
                        observer.observe(model, event(token))
                        with self.assertRaises(TextObserverError):
                            observer.flush()
                    else:
                        with self.assertRaises(TextObserverError):
                            observer.observe(model, event(token))
                    self.assertTrue(observer.sink_poisoned)
                    self.assertEqual(recorder.snapshot(), prefix)
                    self.assertEqual(execution_counts(model), before)
                    state = transition.state
                original, calls = recorder.snapshot(), sink.calls
                observer.set_level(LogLevel.OFF)
                with self.assertRaises(TextObserverError):
                    observer.observe(model, Event.Message(LogLevel.OFF, 3, 'still poisoned'))
                self.assertEqual(sink.calls, calls)
                recorder.stop_with_error(ModelError('observer error after property failure'))
                self.assertEqual(recorder.snapshot(), original)
                self.assertEqual(original.termination, 'property_failed')
                self.assertEqual(execution_counts(model), (0, 3, 4, 3, 6))

    def test_policy_skips_stay_explicit_and_do_not_authorize_full_recording(self):
        for sequence, policy, state_calls, turn_calls, skipped in (
            (1, CheckPolicy(2), 1, 1, ('stateless.state_checks',)),
            (2, CheckPolicy(2), 2, 1, ()),
            (1, CheckPolicy(1, False), 2, 0, ('stateless.transition_checks',)),
        ):
            with self.subTest(sequence=sequence, policy=policy):
                model = ApplicationModel()
                initial = check_initial(model, 0)
                recorder = Recorder.with_checked_initial_at(initial, sequence - 1)
                transition = apply(model, 0, 1)
                token = check_turn(model, 0, 1, transition, sequence, policy)
                self.assertFalse(token.full_checking)
                self.assertEqual(tuple(c.id for c in token.checks if c.status == 'skipped'), skipped)
                writer = io.BytesIO()
                observer = TextObserver(writer, 'policy', ObservationOptions(LogLevel.WARN))
                before = execution_counts(model)
                observer.observe(model, event(token))
                self.assertEqual(bool(writer.getvalue()), bool(skipped))
                for name in skipped:
                    self.assertIn(f'check="{name}":Skipped'.encode(), writer.getvalue())
                prefix = recorder.snapshot()
                with self.assertRaisesRegex(ModelError, 'full checking'):
                    recorder.observe_checked(token)
                self.assertEqual(execution_counts(model), before)
                self.assertEqual(before, (0, 1, state_calls, turn_calls, 2))
                self.assertEqual(recorder.snapshot().steps, prefix.steps)
                self.assertEqual(recorder.snapshot().initial_checks, prefix.initial_checks)
                self.assertEqual(recorder.snapshot().termination, 'model_error')

    def test_missing_observation_is_a_gap_even_when_diagnostic_events_are_printed(self):
        model = ApplicationModel()
        recorder = Recorder.with_checked_initial(check_initial(model, 0))
        writer = io.BytesIO()
        observer = TextObserver(writer, 'gap', ObservationOptions(LogLevel.DEBUG))
        first = apply(model, 0, 1)
        first_token = check_turn(model, 0, 1, first, 1)
        observer.observe(model, event(first_token))  # Intentionally absent from Recorder.
        second = apply(model, first.state, 1)
        second_token = check_turn(model, first.state, 1, second, 2)
        observer.observe(model, event(second_token))
        before = execution_counts(model)
        with self.assertRaisesRegex(ModelError, 'sequence is missing or reordered'):
            recorder.observe_checked(second_token)
        self.assertEqual(execution_counts(model), before)
        self.assertEqual(recorder.observed_steps(), 0)
        self.assertEqual(recorder.snapshot().initial_state, b'0')
        self.assertEqual(recorder.snapshot().steps, ())
        self.assertEqual(recorder.snapshot().termination, 'model_error')
        self.assertEqual(len(writer.getvalue().splitlines()), 2)

    def test_empty_completed_batches_are_not_policy_skips(self):
        class NoChecks(ApplicationModel):
            def check_state(self, state):
                self.calls['state_check'] += 1
                return ()

            def check_transition(self, before, input, transition):
                self.calls['turn_check'] += 1
                return ()

        model = NoChecks()
        initial = check_initial(model, 0)
        recorder = Recorder.with_checked_initial(initial)
        first = apply(model, 0, 1)
        full = check_turn(model, 0, 1, first, 1)
        self.assertTrue(full.full_checking)
        self.assertEqual((initial.checks, full.checks), ((), ()))
        recorder.observe_checked(full)
        writer = io.BytesIO()
        observer = TextObserver(writer, 'empty', ObservationOptions(LogLevel.WARN))
        observer.observe(model, event(full))
        self.assertEqual(writer.getvalue(), b'')
        second = apply(model, first.state, 1)
        skipped = check_turn(model, first.state, 1, second, 2, CheckPolicy(1, False))
        self.assertEqual(skipped.checks,
                         (Check('stateless.transition_checks', 'skipped', 'disabled by policy'),))
        observer.observe(model, event(skipped))
        self.assertIn(b'Warn stream="empty"', writer.getvalue())
        prefix = recorder.snapshot()
        with self.assertRaisesRegex(ModelError, 'full checking'):
            recorder.observe_checked(skipped)
        self.assertEqual(recorder.snapshot().steps, prefix.steps)
        self.assertEqual(execution_counts(model), (0, 2, 3, 1, 4))

    def test_diagnostic_events_and_views_cannot_forge_checked_authority(self):
        model = ApplicationModel()
        initial = check_initial(model, 0)
        transition = apply(model, 0, 1)
        token = check_turn(model, 0, 1, transition, 1)
        forged = Event.Transition(1, 0, 1, Transition(999, (12345,)), (Check('forged'),))
        for diagnostic in (event(token), forged, token.observation(), Event.Checkpoint(0, initial.state, initial.checks)):
            with self.subTest(diagnostic=type(diagnostic).__name__):
                recorder = Recorder.with_checked_initial(initial)
                before = model.calls.copy()
                with self.assertRaisesRegex(ModelError, 'authentic CheckedTurn'):
                    recorder.observe_checked(diagnostic)
                self.assertEqual(model.calls, before)
                self.assertEqual(recorder.snapshot().steps, ())
        with self.assertRaisesRegex(ModelError, 'authentic CheckedInitial'):
            Recorder.with_checked_initial(Event.Checkpoint(0, initial.state, initial.checks))
        # A real token remains reusable in independent recorders after diagnostics.
        left = Recorder.with_checked_initial(initial)
        right = Recorder.with_checked_initial(initial)
        before = execution_counts(model)
        left.observe_checked(token)
        right.observe_checked(token)
        self.assertEqual(left.snapshot(), right.snapshot())
        self.assertEqual(execution_counts(model), before)

    def test_actual_application_result_is_not_replaced_when_reference_replay_disagrees(self):
        class HostApplication(ApplicationModel):
            def step(self, state, input):
                self.calls['step'] += 1
                return Transition(7, (99, 100), Disposition('ignored', 'host result'))

        model = HostApplication()
        initial = check_initial(model, 0)
        recorder = Recorder.with_checked_initial(initial)
        actual = apply(model, 0, 1)
        token = check_turn(model, 0, 1, actual, 1)
        before = execution_counts(model)
        recorder.observe_checked(token)
        writer = io.BytesIO()
        observer = TextObserver(writer, 'host', ObservationOptions(
            LogLevel.TRACE, SnapshotPolicy.EVERY_TRANSITION), EncodedPayloads(32))
        observer.observe(model, event(token))
        self.assertEqual(execution_counts(model), before)
        self.assertEqual(before, (0, 1, 2, 1, 2))
        self.assertEqual(model.last_checked, (0, 1, actual))
        trace = recorder.snapshot()
        self.assertEqual(trace.termination, 'property_failed')
        self.assertEqual(trace.steps[0].outputs, (b'99', b'100'))
        self.assertEqual(trace.steps[0].post_state, b'7')
        self.assertEqual(trace.steps[0].disposition, Disposition('ignored', 'host result'))
        self.assertEqual(trace.steps[0].checks, token.checks)
        self.assertEqual(writer.getvalue().decode(),
                         'Error stream="host" event=transition sequence=1 '
                         'disposition=Ignored("host result") outputs=2 checks=2 '
                         'check="state":Passed '
                         'check="actual-output":Failed("supplied outputs differ") '
                         'input=hex:31 output[0]=hex:3939 output[1]=hex:313030 post_state=hex:37\n')
        playback = ApplicationModel()
        report = replay_with_observations_bounded(playback, trace)
        self.assertEqual((report.outcome, report.field, report.steps_verified), ('diverged', 'disposition', 0))
        self.assertFalse(report.failure_reproduced)
        self.assertEqual(execution_counts(playback), (0, 1, 2, 1, 0))
