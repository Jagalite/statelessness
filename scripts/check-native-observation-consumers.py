    attempt.watch('typescript-built-dist', work / 'typescript-package/dist')
    attempt.run('typescript-pack', [npm, 'pack', '--ignore-scripts', '--pack-destination', packages], work / 'typescript-package')
    tarball, = packages.glob('*.tgz')
