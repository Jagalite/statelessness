def source_module(name, path):
    """Execute these source bytes, never a timestamp or unchecked-hash .pyc.

    Callers seal/watch the source tree. -B disables cache writes, not reads,
    so exec_module's cache-aware SourceFileLoader is intentionally not used.
    """
    path = Path(path)
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    exec(compile(path.read_bytes(), str(path), 'exec'), module.__dict__)
    return module


def helper(name):
    """Load a parent-owned helper from the same sealed scripts directory."""
    return source_module(name, ROOT / 'scripts' / (name + '.py'))


def utilities():
    # importlib consumers need not register this module in sys.modules.
    return SimpleNamespace(**globals())


def canonical(value):
    return (json.dumps(value, ensure_ascii=True, sort_keys=True,
                       separators=(',', ':'), allow_nan=False) + '\n').encode('ascii')


def sha(data):
    return hashlib.sha256(data).hexdigest()


def strict_json(raw):
    def pairs(items):
        result = {}
        for key, value in items:
            if key in result:
                raise ValueError('duplicate JSON key: ' + key)
            result[key] = value
        return result
    def constant(value):
        raise ValueError('non-finite JSON constant: ' + value)
    # Decode strictly: malformed output remains preserved in the original log.
    return json.loads(raw.decode('utf-8') if isinstance(raw, bytes) else raw,
                      object_pairs_hook=pairs, parse_constant=constant)


def write_new(path, raw):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('xb') as stream:
        stream.write(raw)
        stream.flush()
        os.fsync(stream.fileno())


def identity(path):
    info = path.lstat()
    mode = stat.S_IMODE(info.st_mode)
    if stat.S_ISLNK(info.st_mode):
        raw = os.fsencode(os.readlink(path))
        return dict(type='symlink', mode=mode, size_bytes=len(raw), sha256=sha(raw),
                    target=os.readlink(path))
    if not stat.S_ISREG(info.st_mode):
        raise ValueError('required file is not regular or a symlink: ' + str(path))
    with path.open('rb') as stream:
        checksum = hashlib.file_digest(stream, 'sha256').hexdigest()
    return dict(type='regular', mode=mode, size_bytes=info.st_size, sha256=checksum)


def executable_identity(path):
    resolved = path.resolve(strict=True)
    return dict(path=str(path), link=identity(path), resolved=str(resolved),
                file=identity(resolved))


def tree_identity(root):
    if not root.is_dir():
        raise ValueError('required tree is missing or not a directory: ' + str(root))
    return {str(p.relative_to(root)): identity(p) for p in sorted(root.rglob('*'))
            if p.is_file() or p.is_symlink()}


def manifest(root, value):
    raw = canonical(value)
    target = root / RECEIPTS / 'manifests' / (sha(raw) + '.json')
    try:
        write_new(target, raw)
    except FileExistsError:
        if target.read_bytes() != raw:
            raise ValueError('content-addressed manifest collision')
    return dict(path=str(target.relative_to(root)), sha256=sha(raw), size_bytes=len(raw))


def git(root, *args, input=None):
    result = subprocess.run(['git', *args], cwd=root, input=input,
                            stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=False)
    if result.returncode:
        raise RuntimeError('git identity command failed: ' + repr(result.stderr))
    return result.stdout


def receipt_path(name):
    return name.startswith(str(RECEIPTS) + '/')


def ignored_build_output(name):
    """Only consulted for paths Git itself marks ignored; tracked files always count."""
    parts = Path(name).parts
    # build.rs recursively hashes Rust source roots, even ignored descendants.
    if name.startswith('src/') or (len(parts) > 2 and parts[0] == 'crates' and parts[2] == 'src'):
        return False
    return (name.startswith(('target/', 'validation/corpus/target/', 'typescript/node_modules/',
                             'typescript/dist/', 'typescript/examples/build/', 'python/build/',
                             'python/dist/', 'go/bin/', '.build/', '.swiftpm/',
                             'bindings/.build/', 'bindings/.swiftpm/',
                             'bindings/swift-v2/.build/', 'bindings/swift-v2/.swiftpm/'))
            or ('__pycache__' in parts and name.endswith(('.pyc', '.pyo')))
            or (name.startswith('python/src/') and any(p.endswith('.egg-info') for p in parts))
            or (name.startswith('swift/') and any(p in ('.build', '.swiftpm') for p in parts))
            or (len(parts) == 2 and parts[0] == 'typescript' and name.endswith('.tgz')))


def source_snapshot(root):
    tracked = git(root, 'ls-files', '--cached', '-z').split(b'\0')
    others = git(root, 'ls-files', '--others', '--exclude-standard', '-z').split(b'\0')
    ignored = git(root, 'ls-files', '--others', '--ignored', '--exclude-standard', '-z').split(b'\0')
    names = {os.fsdecode(p) for p in tracked + others if p}
    names.update(os.fsdecode(p) for p in ignored if p and not ignored_build_output(os.fsdecode(p)))
    rows = {}
    for name in sorted(names):
        if receipt_path(name):
            continue
        try:
            rows[name] = identity(root / name)
        except OSError as error:
            rows[name] = dict(type='missing', error=repr(error))
    return rows


def committed_snapshot(root, commit):
    resolved = git(root, 'rev-parse', '--verify', commit + '^{commit}').decode().strip()
    entries = []
    for raw in git(root, 'ls-tree', '-rz', '--full-tree', resolved).split(b'\0'):
        if not raw:
            continue
        meta, name_raw = raw.split(b'\t', 1)
        mode, kind, oid = meta.decode().split()
        name = os.fsdecode(name_raw)
        if receipt_path(name):
            continue
        if kind != 'blob' or mode not in ('100644', '100755', '120000'):
            raise ValueError('unsupported committed input type: ' + name)
        entries.append((name, mode, oid))
    # One batch retains binary content exactly, including NUL/newline bytes.
    stream = io.BytesIO(git(root, 'cat-file', '--batch',
                           input=''.join(oid + '\n' for _, _, oid in entries).encode()))
    rows = {}
    for name, mode, oid in entries:
        header = stream.readline().decode().split()
        if len(header) != 3 or header[:2] != [oid, 'blob']:
            raise ValueError('invalid committed blob response: ' + name)
        raw = stream.read(int(header[2]))
        if stream.read(1) != b'\n':
            raise ValueError('truncated committed blob: ' + name)
        row = dict(type='symlink' if mode == '120000' else 'regular',
                   mode=0o777 if mode == '120000' else int(mode[-3:], 8),
                   size_bytes=len(raw), sha256=sha(raw))
        if mode == '120000':
            row['target'] = os.fsdecode(raw)
        rows[name] = row
    return resolved, rows


def assert_sources(actual, expected):
    added, missing = sorted(actual.keys() - expected.keys()), sorted(expected.keys() - actual.keys())
    changed = sorted(k for k in actual.keys() & expected.keys() if actual[k] != expected[k])
    if added or missing or changed:
        raise ValueError(f'source tree differs: added={added}, missing={missing}, changed={changed}')


def validate_fixture(fixture):
    if not isinstance(fixture, dict) or fixture.get('schema') != 'statelessness.observation.v1':
        raise ValueError('incorrect observation fixture schema')
    cases = fixture.get('cases')
    if not isinstance(cases, list) or not cases:
        raise ValueError('fixture must contain independently authored cases')
    ids = set()
    for case in cases:
        if not isinstance(case, dict) or not isinstance(case.get('id'), str) or not case['id']:
            raise ValueError('fixture case has no id')
        if case['id'] in ids:
            raise ValueError('duplicate fixture id: ' + case['id'])
        ids.add(case['id'])
        expected = case.get('expected')
        if not isinstance(expected, dict) or set(expected) - {'record_text'} != RESULT_KEYS - {'id'}:
            raise ValueError('incomplete or unknown expected fields: ' + case['id'])
        validate_case(dict(id=case['id'], **{k: v for k, v in expected.items() if k != 'record_text'}))
        raw = bytes.fromhex(expected['record_hex'])
        if 'record_text' in expected and expected['record_text'].encode('utf-8') != raw:
            raise ValueError('explanatory record_text differs from record_hex: ' + case['id'])
        events, options = case.get('events'), case.get('options')
        if not isinstance(events, list) or not events or not isinstance(options, dict):
            raise ValueError('missing events/options: ' + case['id'])
        maximum = options.get('max_record_bytes', 1048576)
        if type(maximum) is not int or maximum < 0:
            raise ValueError('invalid record bound: ' + case['id'])
        # Independent admission sanity for a single successful record. Multi-event
        # totals and custom formatter newlines are deliberately not split/normalized.
        if len(events) == 1 and expected['error_stage'] is None and len(raw) > maximum:
            raise ValueError('single successful record exceeds its byte bound: ' + case['id'])
    return fixture


def validate_case(case):
    if not isinstance(case, dict) or set(case) != RESULT_KEYS:
        raise ValueError('result case has missing or extra fields')
    if not isinstance(case['id'], str) or not case['id']:
        raise ValueError('invalid result id')
    encoded = case['record_hex']
    if not isinstance(encoded, str) or len(encoded) % 2 or any(c not in '0123456789abcdef' for c in encoded):
        raise ValueError('record_hex must be canonical lowercase hex')
    if not isinstance(case['callbacks'], list) or any(type(c) is not str for c in case['callbacks']):
        raise ValueError('callbacks must be an ordered string array')
    if case['error_stage'] is not None and (type(case['error_stage']) is not str or case['error_stage'] not in ERROR_STAGES):
        raise ValueError('unknown error stage')
    if type(case['sink_poisoned']) is not bool:
        raise ValueError('sink_poisoned must be a boolean')


def expected_result(fixture, language):
    validate_fixture(fixture)
    return dict(schema='statelessness.observation-results.v1', language=language,
                cases=[dict(id=c['id'], **{k: v for k, v in c['expected'].items() if k != 'record_text'})
                       for c in fixture['cases']])


def validate_result(fixture, language, actual):
    expected = expected_result(fixture, language)
    if not isinstance(actual, dict) or set(actual) != {'schema', 'language', 'cases'}:
        raise ValueError('result root has missing or extra fields')
    if actual['schema'] != expected['schema'] or actual['language'] != language:
        raise ValueError('result schema or language differs')
    if not isinstance(actual['cases'], list):
        raise ValueError('cases must be a list')
    for case in actual['cases']:
        validate_case(case)
    # JSON's scalar kinds matter: Python equality alone equates true with 1.
    # Object order/JSON whitespace carry no contract; arrays/text/hex are exact.
    if canonical(actual) != canonical(expected):
        raise ValueError(language + ': exact observation contract mismatch')
    return len(actual['cases'])


def negative_controls(fixture, actual, language):
    """Mutate only copies of independent data; count validator checks separately."""
    validate_result(fixture, language, actual)
    controls = []
    def rejects(name, candidate_fixture, candidate):
        try:
            validate_result(candidate_fixture, language, candidate)
        except (ValueError, TypeError):
            controls.append(name)
            return
        raise AssertionError('validator accepted negative control: ' + name)
    for name, field, value in (
        ('record-bytes', 'record_hex', actual['cases'][0]['record_hex'] + '00'),
        ('callback-count', 'callbacks', actual['cases'][0]['callbacks'] + ['unexpected:0']),
        ('error-stage', 'error_stage', 'record_limit' if actual['cases'][0]['error_stage'] is None else None),
        ('sink-health', 'sink_poisoned', not actual['cases'][0]['sink_poisoned']),
        ('boolean-type', 'sink_poisoned', int(actual['cases'][0]['sink_poisoned'])),
        ('case-id', 'id', actual['cases'][0]['id'] + '-wrong'),
    ):
        changed = copy.deepcopy(actual); changed['cases'][0][field] = value
        rejects(name, fixture, changed)
    changed = copy.deepcopy(actual); changed['cases'] = changed['cases'][:-1]
    rejects('omitted-case', fixture, changed)
    changed = copy.deepcopy(actual); changed['unclaimed-field'] = True
    rejects('extra-field', fixture, changed)
    changed = copy.deepcopy(fixture)
    changed['cases'][0]['expected']['callbacks'].append('independent-expected-mutation:0')
    rejects('independent-expectation', changed, actual)
    eligible = next((i for i, c in enumerate(fixture['cases'])
                     if len(c['events']) == 1 and c['expected']['error_stage'] is None
                     and c['expected']['record_hex']), None)
    if eligible is None:
        raise ValueError('fixture lacks a successful single-record bound control')
    changed = copy.deepcopy(fixture)
    changed['cases'][eligible]['options']['max_record_bytes'] = len(bytes.fromhex(
        changed['cases'][eligible]['expected']['record_hex'])) - 1
    rejects('independent-record-byte-bound', changed, actual)
    return controls


def clean_environment(work):
    env = dict(os.environ)
    for key in list(env):
        if key.startswith(('STATELESS_', 'CARGO_ENCODED_', 'DYLD_', 'LD_', 'npm_config_')) or key in (
                'RUSTC', 'RUSTDOC', 'RUSTFLAGS', 'RUSTDOCFLAGS', 'RUSTC_WRAPPER',
                'RUSTC_WORKSPACE_WRAPPER', 'PYTHONPATH', 'PYTHONHOME', 'NODE_OPTIONS',
                'NODE_PATH', 'GOFLAGS', 'GOENV'):
            env.pop(key, None)
    env.update(PYTHONDONTWRITEBYTECODE='1', PYTHONNOUSERSITE='1', PYTHONPATH='',
               CGO_ENABLED='0', GOPROXY='off', GOSUMDB='off', GOTOOLCHAIN='local',
               GOWORK='off', GOFLAGS='', GOENV='off', GODEBUG='panicnil=0', CARGO_INCREMENTAL='0',
               GOCACHE=str(work / 'go-cache'), GOMODCACHE=str(work / 'go-mod-cache'),
               npm_config_cache=str(work / 'npm-cache'))
    return env


class Attempt:
    """One immutable attempt directory with exclusive, raw per-command logs."""
    def __init__(self, root, output, expected_commit, scope, timeout=900):
        self.root = root.resolve(); self.output = output.resolve()
        base = self.root / RECEIPTS
        if not self.output.is_relative_to(base) or self.output == base or self.output.is_relative_to(base / 'manifests'):
            raise ValueError('output must be a new attempt below ' + str(base))
        self.output.mkdir(parents=True, exist_ok=False)
        self.work = Path(tempfile.mkdtemp(prefix='stateless-observation-')).resolve()
        if self.work.is_relative_to(self.root):
            raise ValueError('staging directory must be outside the checkout')
        self.env = clean_environment(self.work); self.timeout = timeout
        self.initial = None; self.inputs = {}; self.staged = {}; self.staged_roots = {}
        self.expected_commit = expected_commit
        self.report = dict(schema='statelessness.observation-qualification.v1', scope=scope,
                           started_ns=time.time_ns(), source_root=str(self.root), workspace=str(self.work),
                           requested_commit=expected_commit, commands=[], status='running',
                           language_executed_cases={}, validator_controls={}, scope_gaps=[])
        write_new(self.output / 'attempt.json', canonical(self.report))

    def seal(self):
        commit, expected = committed_snapshot(self.root, self.expected_commit)
        self.report['expected_commit'] = commit
        self.report['committed_source'] = manifest(self.root, expected)
        self.initial = source_snapshot(self.root)
        self.report['source_before'] = manifest(self.root, self.initial)
        self.check_head('head_before')
        assert_sources(self.initial, expected)
        fixture = validate_fixture(strict_json((self.root / FIXTURE).read_bytes()))
        self.report['fixture'] = dict(path=str(FIXTURE), **identity(self.root / FIXTURE))
        return fixture

    def check_head(self, key):
        head, committed = committed_snapshot(self.root, 'HEAD')
        _, pinned = committed_snapshot(self.root, self.report['expected_commit'])
        # Receipt-only commits may advance HEAD while every consumed committed
        # file remains identical to the original source pin.
        assert_sources(committed, pinned)
        self.report[key] = head
        self.report[key + '_source'] = manifest(self.root, committed)

    def check_inputs(self):
        for label, (path, before) in getattr(self, 'inputs', {}).items():
            after = (executable_identity(path) if 'file' in before
                     else dict(path=str(path), tree=tree_identity(path)))
            if before != after:
                raise ValueError('input changed before/after command: ' + label)

    def watch(self, label, path):
        path = Path(path).absolute()
        row = executable_identity(path) if path.is_file() else dict(path=str(path), tree=tree_identity(path))
        if label in self.inputs and self.inputs[label] != (path, row):
            raise ValueError('watched input changed before reuse: ' + label)
        self.inputs[label] = (path, row)
        return row

    def register_generated(self, path, label):
        """Admit an explicitly authored input once, before its first consumer.

        Only regular files inside this attempt's external workspace qualify.
        Neither repeated labels nor repeated paths may rebaseline changed bytes.
        Directory membership is still enforced for every copied source tree.
        """
        path = Path(path).absolute()
        if not path.is_relative_to(self.work) or path.resolve(strict=True) != path:
            raise ValueError('generated input must be a nonsymlink staged file: ' + str(path))
        row = identity(path)
        if row['type'] != 'regular':
            raise ValueError('generated input must be regular: ' + str(path))
        key = str(path)
        previous = self.staged.get(key)
        expected = dict(origin='generated-input', label=label, identity=row)
        if previous is not None and previous != expected:
            raise ValueError('generated input cannot rebaseline an existing identity: ' + key)
        self.watch('generated:' + label, path)
        self.staged[key] = expected
        return row

    def staged_snapshot(self):
        rows = {}
        for path, expected in getattr(self, 'staged', {}).items():
            row = dict(expected)
            try:
                row['identity'] = identity(Path(path))
            except (OSError, ValueError) as error:
                row['identity'] = dict(type='unavailable', error=repr(error))
            rows[path] = row
        # Registered file hashes cannot detect new sibling Go/Swift sources.
        # Scan each staged source directory as well, excluding only the build
        # products explicitly permitted for that particular package layout.
        for base, prefix in getattr(self, 'staged_roots', {}).items():
            root = Path(base)
            if not root.is_dir() or root.is_symlink():
                rows[base] = dict(origin='unavailable-staged-directory')
                continue
            for directory, dirs, files in os.walk(root, followlinks=False):
                base_path = Path(directory)
                retained = []
                for name in dirs:
                    child = base_path / name
                    relative = str(child.relative_to(root))
                    if child.is_symlink():
                        files.append(name)
                    elif not staged_build_output(prefix, relative):
                        retained.append(name)
                dirs[:] = retained
                for name in files:
                    child = base_path / name
                    relative = str(child.relative_to(root))
                    path = str(child.absolute())
                    if path not in rows and not staged_build_output(prefix, relative):
                        rows[path] = dict(origin='unexpected-staged-input', identity=identity(child))
        return rows

    def run(self, name, argv, cwd=None, overlay=None, timeout=None, accept_failure=False):
        if self.initial is not None:
            self.check_head('head_latest')
            assert_sources(source_snapshot(self.root), self.initial)
        self.check_inputs()
        argv = list(map(str, argv)); cwd = Path(cwd or self.work)
        if hasattr(self, 'staged'):
            assert_sources(self.staged_snapshot(), self.staged)
        env = dict(self.env, **(overlay or {}))
        executable = shutil.which(argv[0], path=env.get('PATH'))
        if executable is None:
            raise ValueError('command executable not found: ' + argv[0])
        before = executable_identity(Path(executable))
        index = len(self.report['commands']) + 1
        directory = self.output / 'commands' / f'{index:04d}-{name}'
        directory.mkdir(parents=True, exist_ok=False)
        stdout, stderr = directory / 'stdout.bin', directory / 'stderr.bin'
        entry = dict(name=name, argv=argv, cwd=str(cwd), started_ns=time.time_ns(),
                     executable_before=before, environment_overlay=overlay or {},
                     environment={k: env.get(k) for k in ('PATH', 'CGO_ENABLED', 'GOPROXY',
                     'GOTOOLCHAIN', 'GOWORK', 'GOFLAGS', 'GOENV', 'GODEBUG', 'RUSTUP_TOOLCHAIN',
                     'CARGO_HOME', 'CARGO_TARGET_DIR', 'CARGO_INCREMENTAL', 'SDKROOT',
                     'DEVELOPER_DIR', 'PYTHONPATH', 'PYTHONNOUSERSITE')})
        self.report['commands'].append(entry)
        if getattr(self, 'staged', None):
            entry['staged_inputs_before'] = manifest(self.root, self.staged)
        write_new(directory / 'started.json', canonical(entry))
        print('Starting ' + name, flush=True)
        error = None
        process_control = helper('observation_process')
        try:
            with stdout.open('xb') as out, stderr.open('xb') as err:
                # Keep Kyoto's PGID. The helper tracks only owned descendants;
                # it never signals the shared scheduler process group.
                process = subprocess.Popen(argv, cwd=cwd, env=env, stdout=out, stderr=err)
                entry['exit_code'] = process_control.wait_owned(
                    process, self.timeout if timeout is None else timeout, entry)
        except BaseException as failure:
            error = failure; entry['error'] = repr(failure)
        finally:
            for key, path in (('stdout', stdout), ('stderr', stderr)):
                if path.exists():
                    entry[key] = dict(path=str(path.relative_to(self.output)))
                    if entry.get('raw_logs_stable') is True:
                        entry[key].update(identity(path))
            entry['finished_ns'] = time.time_ns()
            try:
                entry['executable_after'] = executable_identity(Path(executable))
                entry['executable_unchanged'] = before == entry['executable_after']
                if not entry['executable_unchanged']:
                    raise ValueError('executed file changed during ' + name)
                if self.initial is not None:
                    self.check_head('head_latest')
                    after = source_snapshot(self.root)
                    entry['source_after'] = manifest(self.root, after)
                    assert_sources(after, self.initial)
                if getattr(self, 'staged', None):
                    staged_after = self.staged_snapshot()
                    entry['staged_inputs_after'] = manifest(self.root, staged_after)
                    assert_sources(staged_after, self.staged)
                self.check_inputs()
            except BaseException as failure:
                error = error or failure; entry['identity_error'] = repr(failure)
            write_new(directory / 'finished.json', canonical(entry))
        if error is not None:
            raise error
        if entry['exit_code'] and not accept_failure:
            raise RuntimeError(name + ' failed; see raw stdout/stderr in ' + str(directory))
        return stdout.read_bytes(), stderr.read_bytes(), entry

    def collect_raw_logs(self):
        """Reconcile every writer's journals before hashing any final raw log.

        The outer Go process cannot certify an unconfirmed writer discovered
        only by its nested -exec wrapper. Missing/partial wrappers remain failed
        evidence with a path inventory, never a new final hash baseline.
        """
        paths = {str(p.relative_to(self.output)): p
                 for p in sorted(self.output.rglob('*.bin'))
                 if p.name in ('stdout.bin', 'stderr.bin')}
        self.report['raw_log_paths'] = sorted(paths)
        exec_dir = self.output / 'go-executables'
        nested_directories = sorted(exec_dir.iterdir()) if exec_dir.exists() else []
        self.report['nested_go_paths'] = [str(p.relative_to(self.output)) for p in nested_directories]
        expected_logs, expected_journals = {}, set()

        def reconcile(base, commands):
            if not isinstance(commands, list):
                raise ValueError('missing command journal list: ' + str(base))
            for index, entry in enumerate(commands, 1):
                directory = base / 'commands' / f'{index:04d}-{entry["name"]}'
                started_path, finished_path = directory / 'started.json', directory / 'finished.json'
                expected_journals.update((started_path, finished_path))
                started = strict_json(started_path.read_bytes())
                finished = strict_json(finished_path.read_bytes())
                keys = ('name', 'argv', 'cwd', 'started_ns', 'executable_before',
                        'environment_overlay', 'environment')
                start_fields = {key: entry[key] for key in keys}
                if 'staged_inputs_before' in entry:
                    start_fields['staged_inputs_before'] = entry['staged_inputs_before']
                if canonical(started) != canonical(start_fields) or canonical(finished) != canonical(entry):
                    raise ValueError('started/finished/receipt command disagreement: ' + str(directory))
                if (entry.get('raw_logs_stable') is not True
                        or entry.get('process_tree_termination_confirmed') is not True):
                    raise ValueError('raw logs require confirmed descendant termination: ' + str(directory))
                for stream in ('stdout', 'stderr'):
                    path = directory / (stream + '.bin')
                    claim = entry[stream]
                    if claim.get('path') != str(path.relative_to(base)):
                        raise ValueError('raw log path disagrees with command: ' + str(directory))
                    expected_logs[str(path.relative_to(self.output))] = {
                        k: v for k, v in claim.items() if k != 'path'}

        reconcile(self.output, self.report['commands'])
        nested = []
        if nested_directories:
            for directory in nested_directories:
                receipt_path = directory / 'receipt.json'
                receipt = strict_json(receipt_path.read_bytes())
                commands = receipt.get('commands')
                if (not isinstance(commands, list) or len(commands) != 1
                        or commands[0].get('name') != 'test-executable'):
                    raise ValueError('incomplete nested Go command receipt: ' + str(receipt_path))
                reconcile(directory, commands)
                command = commands[0]
                code, error = receipt.get('exit_code'), receipt.get('error')
                status = 'failed' if error or code else 'passed'
                if (type(code) is not int or receipt.get('status') != status
                        or (error is None and command.get('exit_code') != code)):
                    raise ValueError('nested Go status disagrees with command: ' + str(receipt_path))
                if status == 'passed' and (receipt.get('before') != receipt.get('after')
                        or receipt.get('before') != command.get('executable_before')
                        or receipt.get('after') != command.get('executable_after')
                        or command.get('executable_unchanged') is not True
                        or any(command.get(key) for key in ('error', 'identity_error'))):
                    raise ValueError('nested Go passed receipt contains a failed command: ' + str(receipt_path))
                nested.append(dict(path=str(receipt_path.relative_to(self.output)), status=status))
        self.report['nested_go_receipts'] = nested
        journals = set(self.output.rglob('started.json')) | set(self.output.rglob('finished.json'))
        if journals != expected_journals or paths.keys() != expected_logs.keys():
            raise ValueError('unreconciled command journals or raw log paths')
        # Every outer AND nested owner now confirms stable logs. Only here read
        # their bytes; failed but stable commands still retain exact raw hashes.
        logs = {name: identity(path) for name, path in paths.items()}
        assert_sources(logs, expected_logs)
        return logs, any(row['status'] != 'passed' for row in nested)

    def finish(self, error=None):
        try:
            after = source_snapshot(self.root)
            self.report['source_after'] = manifest(self.root, after)
            assert_sources(after, self.initial or {})
            self.check_head('head_after')
            self.report['source_unchanged'] = True
        except BaseException as failure:
            self.report['source_error'] = repr(failure); error = error or failure
        rows = {}
        for label, (path, before) in self.inputs.items():
            row = dict(before=before)
            try:
                row['after'] = (executable_identity(path) if 'file' in before
                                else dict(path=str(path), tree=tree_identity(path)))
                row['unchanged'] = before == row['after']
                if not row['unchanged']:
                    raise ValueError('input changed: ' + label)
            except BaseException as failure:
                row['error'] = repr(failure); error = error or failure
            rows[label] = row
        self.report['input_identities'] = manifest(self.root, rows)
        try:
            staged = self.staged_snapshot()
            self.report['staged_inputs_expected'] = manifest(self.root, getattr(self, 'staged', {}))
            self.report['staged_inputs_after'] = manifest(self.root, staged)
            assert_sources(staged, getattr(self, 'staged', {}))
        except BaseException as failure:
            self.report['staged_input_error'] = repr(failure); error = error or failure
        try:
            logs, nested_failed = self.collect_raw_logs()
            self.report['raw_logs'] = manifest(self.root, logs)
            if nested_failed:
                raise ValueError('nested Go executable receipt failed; stable raw logs retained')
        except BaseException as failure:
            self.report['log_collection_error'] = repr(failure); error = error or failure
        self.report.update(status='failed' if error else 'passed', finished_ns=time.time_ns())
        if error:
            self.report['error'] = repr(error)
        write_new(self.output / 'receipt.json', canonical(self.report))
        print(json.dumps(dict(status=self.report['status'], receipt=str(self.output / 'receipt.json'))), flush=True)
        return 1 if error else 0


def staged_build_output(prefix, relative):
    parts = Path(relative).parts
    if '__pycache__' in parts and relative.endswith(('.pyc', '.pyo')):
        return True
    if prefix == 'examples/native-observation/typescript' and parts[0] == 'suffix-build':
        return True
    if prefix == 'python':
        return parts[0] in ('build', 'dist') or any(p.endswith('.egg-info') for p in parts)
    if prefix == 'typescript' or prefix.endswith('/typescript'):
        return parts[0] in ('node_modules', 'dist', 'build') or relative.startswith('examples/build/')
    if prefix == 'swift' or prefix.endswith('/swift'):
        return parts[0] in ('.build', '.swiftpm')
    return False


def stage(attempt, prefix, destination):
    """Copy ONLY committed sealed inputs, never pre-existing ignored build products."""
    prefix = str(prefix).rstrip('/')
    selected = {name: row for name, row in attempt.initial.items()
                if name == prefix or name.startswith(prefix + '/')}
    if not selected:
        raise ValueError('missing staged source: ' + prefix)
    if prefix not in selected:
        attempt.staged_roots[str(destination.absolute())] = prefix
    for name, row in selected.items():
        if row['type'] != 'regular':
            raise ValueError('staged sources must be regular files: ' + name)
        suffix = Path(name).relative_to(prefix)
        target = destination if str(suffix) == '.' else destination / suffix
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(attempt.root / name, target)
        if identity(target) != row:
            raise ValueError('staged copy differs: ' + name)
        entry = dict(origin='committed-source', source=name, identity=row)
        key = str(target.absolute())
        if key in attempt.staged and attempt.staged[key] != entry:
            raise ValueError('staged input would overwrite an earlier identity: ' + name)
        attempt.staged[key] = entry


def require_tool(attempt, name):
    path = shutil.which(name, path=attempt.env.get('PATH'))
    if not path:
        raise ValueError('required tool missing: ' + name)
    attempt.watch('tool:' + name, path)
    if name == 'go' and 'toolchain:go' not in attempt.inputs:
        raw, _, _ = attempt.run('resolve-go-toolchain', [path, 'env', 'GOTOOLDIR'])
        attempt.watch('toolchain:go', Path(raw.decode('utf-8').strip()))
    if name == 'swift' and sys.platform == 'darwin' and 'toolchain:swift' not in attempt.inputs:
        xcrun = shutil.which('xcrun', path=attempt.env.get('PATH'))
        if not xcrun:
            raise ValueError('xcrun is required to identify the selected Swift toolchain')
        for tool in ('swift', 'swiftc', 'clang'):
            raw, _, _ = attempt.run('resolve-' + tool, [xcrun, '--find', tool])
            attempt.watch('toolchain:' + tool, Path(raw.decode('utf-8').strip()))
    return path


def typescript_compiler(attempt, package_directory):
    """Install the sealed lock's development tools inside this Kyoto attempt."""
    package_directory = Path(package_directory)
    if not package_directory.is_relative_to(attempt.work):
        raise ValueError('TypeScript development tooling must be staged outside the checkout')
    npm, node = require_tool(attempt, 'npm'), require_tool(attempt, 'node')
    attempt.run('typescript-dev-dependencies', [npm, 'ci', '--include=dev', '--ignore-scripts',
                '--no-audit', '--no-fund'], package_directory)
    compiler = package_directory / 'node_modules/typescript'
    lock = strict_json((package_directory / 'package-lock.json').read_bytes())
    version = strict_json((compiler / 'package.json').read_bytes())['version']
    if version != lock['packages']['node_modules/typescript']['version']:
        raise ValueError('installed TypeScript version differs from sealed lock')
    attempt.watch('typescript-compiler-tree', compiler)
    attempt.watch('typescript-development-dependencies', package_directory / 'node_modules')
    attempt.report['typescript_development_lock'] = dict(path=str(package_directory / 'package-lock.json'),
        **identity(package_directory / 'package-lock.json'))
    return [node, str(compiler / 'bin/tsc')]


def load_compile(attempt, path):
    path = path.resolve(strict=True)
    attempt.watch('compile-receipt', path)
    receipt = strict_json(path.read_bytes())
    if (receipt.get('schema') != 'statelessness.observation-qualification.v1'
            or receipt.get('scope') != 'rust-compile' or receipt.get('status') != 'passed'
            or receipt.get('expected_commit') != attempt.report['expected_commit']
            or receipt.get('source_before') != attempt.report['source_before']
            or receipt.get('source_after') != attempt.report['source_before']
            or receipt.get('fixture') != attempt.report['fixture']):
        raise ValueError('compile receipt is not bound to this frozen source/fixture')
    binaries = helper('observation_compile_proof').validate_compile(utilities(), attempt, path, receipt)
    attempt.report['compile_receipt'] = dict(path=str(path), **identity(path))
    attempt.report['rust_binaries'] = binaries
    return binaries



