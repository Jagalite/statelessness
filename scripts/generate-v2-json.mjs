// Generate only the existing portable JSON codec, with pure ABI2 value helpers.
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const args=process.argv.slice(2);
const compilerIndex=args.indexOf('--compiler');
const compiler=compilerIndex<0?path.join(root,'typescript/node_modules/typescript/lib/typescript.js'):path.resolve(args[compilerIndex+1]);
const ts=createRequire(import.meta.url)(compiler);
if (ts.version!=='5.8.3') throw new Error('generator requires locked TypeScript 5.8.3');
const source=fs.readFileSync(path.join(root,'typescript/src/json.ts'),'utf8');
const output=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022},reportDiagnostics:true});
if (output.diagnostics?.some(d=>d.category===ts.DiagnosticCategory.Error)) throw new Error('JSON codec transpilation failed');
const text='// Generated by scripts/generate-v2-json.mjs from typescript/src/json.ts.\n'+output.outputText.replace("from './core.js'", "from './v2-values.mjs'");
const destination=path.join(root,'bindings/browser/v2-json.mjs');
if(args.includes('--check')) {if(fs.readFileSync(destination,'utf8')!==text) throw new Error('generated v2 JSON codec is stale');}
else fs.writeFileSync(destination,text);
