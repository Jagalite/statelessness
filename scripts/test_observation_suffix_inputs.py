"""Source-authored suffix build identity controls; execute only through Kyoto."""
from pathlib import Path
import importlib.util
import tempfile
import unittest
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]
DRIVER = ROOT / 'scripts/check-native-observation-consumers.py'
SPEC = importlib.util.spec_from_file_location('suffix_input_driver', DRIVER)
q = importlib.util.module_from_spec(SPEC)
exec(compile(DRIVER.read_bytes(), str(DRIVER), 'exec'), q.__dict__)
suffix = q.helper('observation_suffix')


class SuffixOutputIdentityTests(unittest.TestCase):
    def test_build_outputs_are_watched_before_intervening_commands_or_inventory(self):
        # Real helper ordering, inert literal compiler outputs. No language
        # implementation, compiler, package builder or golden generator runs.
        cases = (
            ('suffix-typescript-build', 'suffix-go-bin'),
            ('suffix-swift-build', 'typescript-consumer/suffix-build/suffix-consumer.js'),
            ('swift-before-runner-inventory', 'suffix-swift-consumer/.build/debug/CheckedConsumer'),
        )
        class BoundaryReached(Exception):
            pass
        for target, relative in cases:
            for mutate in (False, True):
                with self.subTest(target=target, mutate=mutate), tempfile.TemporaryDirectory() as temp:
                    root = Path(temp).resolve() / 'checkout'; root.mkdir()
                    attempt = q.Attempt.__new__(q.Attempt)
                    attempt.root = root; attempt.work = root.parent / 'work'; attempt.work.mkdir()
                    attempt.output = root.parent / 'output'; attempt.output.mkdir()
                    (attempt.output / 'packages').mkdir()
                    attempt.inputs = {}; attempt.staged = {}; attempt.staged_roots = {}; attempt.report = {}
                    contract = dict(schema='statelessness.observation-suffix.v1', scope='synthetic-input-control',
                                    limits={}, observer_max_record_bytes=1024)
                    sources = {str(source): q.canonical(contract) for source, _ in suffix.CONTRACTS.values()}
                    sources.update({
                        'examples/native-checked/python/consumer.py': b'# inert consumer\n',
                        'examples/native-checked/go/main.go': b'package main\n',
                        'examples/native-checked/typescript/consumer.ts': b'export {};\n',
                        'examples/native-checked/swift/Package.swift': b'// inert package\n',
                        'examples/native-checked/swift/Sources/CheckedConsumer/main.swift': b'// inert source\n',
                    })
                    for name, raw in sources.items():
                        path = root / name; path.parent.mkdir(parents=True, exist_ok=True); path.write_bytes(raw)
                    attempt.initial = {name: q.identity(root / name) for name in sources}
                    def produce(name, raw=b'inert generated bytes'):
                        path = attempt.work / name; path.parent.mkdir(parents=True, exist_ok=True); path.write_bytes(raw)
                    for name in ('venv/bin/python', 'venv/lib/package.py', 'go-package/go.mod',
                                 'typescript-consumer/node_modules/@jagalite/statelessness/package.json',
                                 'swift-package/Package.swift', 'tools/node'):
                        produce(name)
                    rust = root.parent / 'rust'; rust.write_bytes(b'inert compiler artifact')
                    binaries = {'native-checked': q.executable_identity(rust)}
                    real_executable_identity = q.executable_identity
                    def change_output():
                        path = attempt.work / relative
                        self.assertTrue(path.is_file(), 'mutation requires a produced output')
                        path.write_bytes(b'persistent mutation before identity reuse')
                    def executable_identity(path):
                        # The first Rust identity read follows Swift output
                        # identification and precedes the final runner inventory.
                        if Path(path) == rust and target == 'swift-before-runner-inventory' and mutate:
                            change_output()
                        return real_executable_identity(path)
                    def run(name, argv, cwd=None, **kwargs):
                        if name == target and mutate:
                            change_output()
                        attempt.check_inputs()
                        q.assert_sources(attempt.staged_snapshot(), attempt.staged)
                        if name == target or name == 'suffix-interrupted-python-record':
                            raise BoundaryReached(name)
                        if name == 'suffix-go-module-graph':
                            modules = [dict(Path='checked-suffix-consumer', Main=True),
                                dict(Path='github.com/Jagalite/statelessness/go', Version='v0.0.0',
                                     Replace=dict(Dir=str(attempt.work / 'go-package')))]
                            return b''.join(q.canonical(m) for m in modules), b'', {}
                        if name == 'suffix-go-build':
                            produce('suffix-go-bin')
                        elif name == 'suffix-typescript-build':
                            produce('typescript-consumer/suffix-build/suffix-consumer.js')
                        elif name == 'suffix-swift-build':
                            produce('suffix-swift-consumer/.build/debug/CheckedConsumer')
                        elif name == 'suffix-swift-bin-path':
                            return str(attempt.work / 'suffix-swift-consumer/.build/debug').encode(), b'', {}
                        return b'', b'', {}
                    attempt.run = run
                    with (patch.object(q, 'require_tool', side_effect=lambda _, name: name),
                          patch.object(q, 'executable_identity', side_effect=executable_identity)):
                        if mutate:
                            with self.assertRaisesRegex(ValueError, '(input changed|watched input changed)'):
                                suffix.qualify(q, attempt, binaries, [str(attempt.work / 'tools/node'), 'inert-tsc'])
                        else:
                            with self.assertRaises(BoundaryReached):
                                suffix.qualify(q, attempt, binaries, [str(attempt.work / 'tools/node'), 'inert-tsc'])


if __name__ == '__main__':
    unittest.main()
