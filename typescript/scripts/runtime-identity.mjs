// Embed a deterministic identity for the TypeScript source inputs to this build.
import {createHash} from 'node:crypto';
import {readFileSync, readdirSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {join} from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const generated = 'src/runtime_identity.ts';
function sources(directory) {
  return readdirSync(join(root, directory), {withFileTypes: true}).flatMap(entry => {
    const path = `${directory}/${entry.name}`;
    if (entry.isSymbolicLink()) throw new Error(`symbolic link in source tree: ${path}`);
    return entry.isDirectory() ? sources(path) : entry.isFile() && path.endsWith('.ts') ? [path] : [];
  });
}
const files = sources('src').filter(path => path !== generated)
  .concat(['package.json', 'package-lock.json', 'tsconfig.json', 'scripts/reference-identity.mjs', 'scripts/runtime-identity.mjs'])
  .sort();
const hash = createHash('sha256');
for (const path of files) {
  const name = Buffer.from(path, 'utf8');
  const content = readFileSync(join(root, path));
  const sizes = Buffer.alloc(16);
  sizes.writeBigUInt64BE(BigInt(name.length), 0);
  sizes.writeBigUInt64BE(BigInt(content.length), 8);
  hash.update(sizes).update(name).update(content);
}
const output = `// Generated by scripts/runtime-identity.mjs; do not edit.\nexport const RUNTIME_SOURCE_BUILD_ID = 'sha256:${hash.digest('hex')}';\n`;
const destination = new URL(`../${generated}`, import.meta.url);
try { if (readFileSync(destination, 'utf8') === output) process.exit(0); } catch {}
writeFileSync(destination, output);
